/**
 * Autonomous writing pilot. All story decisions are generated by the selected
 * LOCAL model, not entered by the user. This controller never publishes to Nexus
 * or treats machine-written continuity notes as owner-approved canon.
 */
data class AutoNovelState(
    val id: String,
    val direction: String = "",
    val phase: String = "CONCEPT",
    val running: Boolean = false,
    val title: String = "",
    val universe: String = "",
    val series: String = "",
    val volume: String = "",
    val premise: String = "",
    val cast: String = "",
    val worldRules: String = "",
    val volumeArc: String = "",
    val chapterPlan: String = "",
    val storySoFar: String = "",
    val chapterIndex: Int = 1,
    val sceneIndex: Int = 0,
    val totalChapters: Int = 8,
    val scenesPerChapter: Int = 3,
    val workspaceId: String = "",
    val lastError: String = "",
    val lastUpdated: Long = System.currentTimeMillis()
) {
    val complete: Boolean get() = phase == "COMPLETE"
}

class AutoNovelStore(context: Context) {
    private val file = File(context.filesDir, "autonomous-novel/state.json").apply {
        parentFile?.mkdirs()
    }
    @Synchronized fun read(): AutoNovelState? {
        if (!file.isFile) return null
        val j = JSONObject(file.readText(Charsets.UTF_8))
        return AutoNovelState(
            id = j.getString("id"), direction = j.optString("direction"),
            phase = j.optString("phase", "CONCEPT"), running = false,
            title = j.optString("title"), universe = j.optString("universe"),
            series = j.optString("series"), volume = j.optString("volume"),
            premise = j.optString("premise"), cast = j.optString("cast"),
            worldRules = j.optString("worldRules"), volumeArc = j.optString("volumeArc"),
            chapterPlan = j.optString("chapterPlan"), storySoFar = j.optString("storySoFar"),
            chapterIndex = j.optInt("chapterIndex", 1), sceneIndex = j.optInt("sceneIndex", 0),
            totalChapters = j.optInt("totalChapters", 8),
            scenesPerChapter = j.optInt("scenesPerChapter", 3),
            workspaceId = j.optString("workspaceId"), lastError = j.optString("lastError"),
            lastUpdated = j.optLong("lastUpdated")
        )
    }
    @Synchronized fun save(s: AutoNovelState): AutoNovelState {
        val update = s.copy(lastUpdated = System.currentTimeMillis())
        val j = JSONObject()
            .put("id", update.id).put("direction", update.direction)
            .put("phase", update.phase).put("title", update.title)
            .put("universe", update.universe).put("series", update.series)
            .put("volume", update.volume).put("premise", update.premise)
            .put("cast", update.cast).put("worldRules", update.worldRules)
            .put("volumeArc", update.volumeArc).put("chapterPlan", update.chapterPlan)
            .put("storySoFar", update.storySoFar)
            .put("chapterIndex", update.chapterIndex).put("sceneIndex", update.sceneIndex)
            .put("totalChapters", update.totalChapters).put("scenesPerChapter", update.scenesPerChapter)
            .put("workspaceId", update.workspaceId).put("lastError", update.lastError)
            .put("lastUpdated", update.lastUpdated)
        val stage = File(file.parentFile, file.name + ".new")
        FileOutputStream(stage).use { stream ->
            stream.write(j.toString().toByteArray(Charsets.UTF_8))
            stream.fd.sync()
        }
        check(stage.renameTo(file)) { "Cannot save the autonomous writing checkpoint" }
        return update
    }
}

class AutonomousNovelEngine(private val context: Context) {
    private val states = AutoNovelStore(context)
    private val manuscripts = WriterWorkspaceStore(context)
    private val director = NarrativeController()

    fun state(): AutoNovelState? = states.read()

    fun newVolume(direction: String = ""): AutoNovelState {
        val prior = states.read()
        require(prior == null || prior.complete) {
            "An unfinished autonomous novel exists. Resume it instead of replacing its progress."
        }
        return states.save(AutoNovelState(
            id = java.util.UUID.randomUUID().toString(),
            direction = direction.take(1200)
        ))
    }

    /** Core loop persists a task boundary before each expensive model call. */
    suspend fun run(
        model: InferenceEngine,
        sampling: WritingSampling,
        onUpdate: (AutoNovelState) -> Unit
    ): AutoNovelState {
        var s = requireNotNull(states.read()) { "Create an autonomous project first" }
        require(!s.complete) { "The current volume is already complete" }
        require(s.totalChapters in 1..40 && s.scenesPerChapter in 1..8)
        try {
            while (!s.complete) {
                coroutineContext.ensureActive()
                checkDeviceBudget()
                s = states.save(s.copy(lastError = "", running = true))
                onUpdate(s)
                s = when (s.phase) {
                    "CONCEPT" -> concept(s, model, sampling)
                    "VOLUME_ARC" -> volumeArc(s, model, sampling)
                    "CHAPTER_PLAN" -> chapterPlan(s, model, sampling)
                    "SCENE" -> writeScene(s, model, sampling)
                    "RECAP" -> chapterRecap(s, model, sampling)
                    else -> error("Unknown autonomous phase: ${s.phase}")
                }
                s = states.save(s)
                onUpdate(s)
            }
            return states.save(s.copy(running = false))
        } catch (cancelled: CancellationException) {
            states.save(s.copy(running = false, lastError = "Paused; progress saved"))
            throw cancelled
        } catch (error: Throwable) {
            states.save(s.copy(running = false, lastError = error.message ?: error.javaClass.simpleName))
            throw error
        }
    }

    private fun checkDeviceBudget() {
        val am = context.getSystemService(Context.ACTIVITY_SERVICE) as android.app.ActivityManager
        val info = android.app.ActivityManager.MemoryInfo()
        am.getMemoryInfo(info)
        check(!info.lowMemory && info.availMem >= 320L * 1024 * 1024) {
            "Device memory pressure: autonomous generation paused safely"
        }
        val power = context.getSystemService(Context.POWER_SERVICE) as android.os.PowerManager
        check(power.currentThermalStatus < android.os.PowerManager.THERMAL_STATUS_SEVERE) {
            "Device temperature too high: generation paused at checkpoint"
        }
        val battery = context.getSystemService(Context.BATTERY_SERVICE) as android.os.BatteryManager
        val level = battery.getIntProperty(android.os.BatteryManager.BATTERY_PROPERTY_CAPACITY)
        check(level <= 0 || level >= 15) {
            "Battery below 15%: generation paused at checkpoint"
        }
    }

    /** All output is from native phone inference; no synthetic fallback passage. */
    private suspend fun infer(
        engine: InferenceEngine,
        sampler: WritingSampling,
        prompt: String,
        outputTokens: Int,
        onChunk: suspend (String) -> Unit = {}
    ): String {
        withContext(Dispatchers.IO) {
            engine.configureSampler(sampler.temperature, sampler.topP, sampler.minP,
                sampler.repetition, sampler.seed)
            engine.resetSession(WritingTestBench.SYSTEM_PROMPT)
        }
        val result = StringBuilder()
        engine.sendUserPrompt(prompt, outputTokens).collect { part ->
            coroutineContext.ensureActive()
            if (part.isNotEmpty()) {
                result.append(part)
                onChunk(part)
            }
        }
        require(result.isNotBlank()) { "Native model produced no writing; checkpoint retained" }
        return result.toString().trim()
    }

    private fun field(text: String, name: String): String {
        val line = text.lineSequence().firstOrNull {
            it.trimStart().startsWith("$name:", ignoreCase = true)
        } ?: return ""
        return line.substringAfter(':').trim()
    }

    private suspend fun concept(s: AutoNovelState, engine: InferenceEngine,
                                sampler: WritingSampling): AutoNovelState {
        val instruction = """
            You are the autonomous creator of a fully ORIGINAL multi-volume literary/web novel.
            Independently invent the premise, title, universe, series, cast, powers/limitations,
            relationships, themes and dramatic engine. Avoid clichés and borrowed franchises.
            Genre, tone and content are your decisions unless an optional direction follows.
            Optional broad direction: ${s.direction.ifBlank { "None. Surprise the reader." }}
            Reply in EXACTLY this field format, each value on a single line:
            TITLE: concise distinctive title
            UNIVERSE: original universe name
            SERIES: series name
            PREMISE: detailed central conflict and creative hook
            CAST: key original people, relationships, motives and secrets
            RULES: binding world rules and limitations
            VOLUME: volume title
            Do not write a chapter yet. Output real creative decisions, never bracket placeholders.
        """.trimIndent()
        var response = infer(engine, sampler, instruction, 1024)
        val required = listOf("TITLE", "UNIVERSE", "PREMISE", "CAST", "RULES")
        if (required.any { field(response, it).isBlank() }) {
            response = infer(engine, sampler,
                "Correct the following original story proposal into the six EXACT single-line " +
                "fields TITLE:, UNIVERSE:, SERIES:, PREMISE:, CAST:, RULES:, VOLUME:. " +
                "Keep its distinctive creative choices. No explanations.\n" + response.take(5000), 1024)
        }
        require(required.all { field(response, it).isNotBlank() }) {
            "Concept response could not be structured; no incomplete universe was committed"
        }
        return s.copy(
            title = field(response, "TITLE"),
            universe = field(response, "UNIVERSE"),
            series = field(response, "SERIES").ifBlank { field(response, "TITLE") },
            premise = field(response, "PREMISE"),
            cast = field(response, "CAST"), worldRules = field(response, "RULES"),
            volume = field(response, "VOLUME").ifBlank { "Volume I" },
            phase = "VOLUME_ARC"
        )
    }

    private suspend fun volumeArc(s: AutoNovelState, engine: InferenceEngine,
                                  sampler: WritingSampling): AutoNovelState {
        val instruction = """
            PLAN A COMPLETE ORIGINAL VOLUME with ${s.totalChapters} linked chapters, each containing
            multiple substantial dramatized scenes. You decide all plot beats; do not ask the user.
            Novel: ${s.title} / ${s.series}; premise: ${s.premise}
            Canonical world mechanics: ${s.worldRules}
            Original cast: ${s.cast}
            Create a distinctive, causal chapter-by-chapter plot with escalation, emotional
            stakes, hidden information, important choices, relationship shifts, and a satisfying
            but non-trivial volume outcome. Give each numbered chapter its own evolving objective.
            These are PRIVATE planning notes, not reader-facing exposition.
            Output only the numbered ${s.totalChapters}-chapter volume plan.
        """.trimIndent()
        val plan = infer(engine, sampler, instruction, 1536)
        require(plan.length >= 120) { "Volume plan too short to guide a complete novel" }
        return s.copy(volumeArc = plan, phase = "CHAPTER_PLAN")
    }

    private suspend fun chapterPlan(s: AutoNovelState, engine: InferenceEngine,
                                    sampler: WritingSampling): AutoNovelState {
        val instruction = """
            AUTONOMOUS CHAPTER DIRECTOR. Generate ${s.scenesPerChapter} specific sequential
            scene objectives for chapter ${s.chapterIndex} of ${s.totalChapters}.
            Book: ${s.title}; World: ${s.worldRules}; Cast: ${s.cast}
            Overall original volume plan: ${s.volumeArc.takeLast(4800)}
            Previously completed events (provisional machine summary): ${s.storySoFar.takeLast(4000)}
            Make each scene change the situation through character decisions, not filler.
            Track chronology and who knows what. Supply concrete setting, conflict, viewpoint,
            dialogue dynamics, consequences, and how it advances THIS chapter.
            Start with TITLE: followed by its chapter title, then SCENE 1:, SCENE 2: and so on.
            Do not write prose yet; make an actionable private chapter plan.
        """.trimIndent()
        val plan = infer(engine, sampler, instruction, 1024)
        require(plan.length > 80) { "Chapter plan too short; generation stopped safely" }
        val title = field(plan, "TITLE").ifBlank { "Chapter ${s.chapterIndex}" }
        val w = if (s.workspaceId.isBlank()) manuscripts.create(
            s.universe, s.series, s.volume, title, s.premise,
            s.cast, s.worldRules + "\n" + s.storySoFar.takeLast(4000),
            "Follow autonomously generated scene ${s.sceneIndex + 1}",
            plan, "Autonomous original fiction"
        , chapterIndex = s.chapterIndex) else requireNotNull(manuscripts.get(s.workspaceId))
        return s.copy(chapterPlan = plan, phase = "SCENE", workspaceId = w.id, sceneIndex = 0)
    }

    private suspend fun writeScene(s: AutoNovelState, engine: InferenceEngine,
                                   sampler: WritingSampling): AutoNovelState {
        val w = requireNotNull(manuscripts.get(s.workspaceId)) { "Chapter workspace disappeared" }
        require(!w.approved) { "Owner-approved chapter cannot be overwritten" }
        val prior = manuscripts.draft(w.id)
        val segmentNumber = s.sceneIndex + 1
        val scene = SceneObjective(
            "scene-${s.chapterIndex}-$segmentNumber", w.id,
            "Chapter ${s.chapterIndex}, scene $segmentNumber",
            "Dramatize scene $segmentNumber of this specific chapter plan: ${s.chapterPlan.takeLast(3600)}",
            emptyList(), chronology = s.chapterIndex.toLong() * 100 + segmentNumber
        )
        val story = ChapterContext(
            s.universe, s.series, s.volume, w.chapter, s.premise,
            s.worldRules, s.cast, s.chapterPlan,
            s.storySoFar.lines().takeLast(14),
            AuthoringProfile(name = "Autonomous", style = "Distinctive fluent novel prose",
                pacing = "Scenes with consequences", dialogue = "Natural and character-specific")
        )
        val prompt = director.makeInstruction(story, scene, prior.takeLast(3200), prior.isNotBlank(),
            maxRecentChars = 3000) +
            "\nWRITE FULL DRAMATIZED NOVEL PROSE, NOT NOTES. No recap, no headings, no premature ending." +
            "\nContinue without repeating already completed passages."
        val current = StringBuilder(prior)
        if (current.isNotEmpty() && !current.endsWith("\n\n")) current.append("\n\n")
        var lastPersisted = SystemClock.elapsedRealtime()
        try {
            infer(engine, sampler, prompt, 1600) { chunk ->
                current.append(chunk)
                val now = SystemClock.elapsedRealtime()
                if (now - lastPersisted >= 1600L) {
                    withContext(Dispatchers.IO) { manuscripts.autosave(w.id, current.toString()) }
                    lastPersisted = now
                }
            }
        } finally {
            // On cancellation and process interruption the committed prose is never discarded.
            withContext(kotlinx.coroutines.NonCancellable + Dispatchers.IO) {
                manuscripts.autosave(w.id, current.toString())
            }
        }
        val nextIndex = s.sceneIndex + 1
        return s.copy(
            sceneIndex = nextIndex,
            phase = if (nextIndex >= s.scenesPerChapter) "RECAP" else "SCENE"
        )
    }

    private suspend fun chapterRecap(s: AutoNovelState, engine: InferenceEngine,
                                     sampler: WritingSampling): AutoNovelState {
        val w = requireNotNull(manuscripts.get(s.workspaceId))
        val chapter = manuscripts.draft(w.id)
        require(chapter.isNotBlank()) { "No actual chapter prose was saved" }
        val quality = QualityGate().check(chapter)
        val instruction = """
            You are maintaining INTERNAL continuity for an original fictional volume.
            From the ACTUAL chapter below, extract only observed events, decisions,
            revealed character knowledge, relationships, unresolved consequences and
            chronology. Never invent missing events. Write a concise factual summary
            and list unresolved threads for the next chapter.
            Context: ${s.premise}; characters: ${s.cast}
            Chapter ${s.chapterIndex} prose:
            ${chapter.takeLast(7600)}
            Output only the factual continuation memo.
        """.trimIndent()
        val memo = infer(engine, sampler, instruction, 750)
        val record = "Chapter ${s.chapterIndex} (provisional; not owner-approved): " +
            memo.take(2100) + "\n"
        val next = s.copy(
            storySoFar = (s.storySoFar + "\n" + record).takeLast(10500),
            chapterIndex = s.chapterIndex + 1, sceneIndex = 0,
            workspaceId = "", chapterPlan = "",
            phase = if (s.chapterIndex >= s.totalChapters) "COMPLETE" else "CHAPTER_PLAN",
            lastError = if (quality.any { it.severity.name == "BLOCK" })
                "Quality warnings on chapter ${s.chapterIndex}: ${quality.map { it.code }.joinToString()}" else ""
        )
        return next
    }
}
